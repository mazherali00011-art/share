-- Run this entire SQL script in Supabase SQL Editor.
-- This creates profiles, messages and a public storage bucket.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  created_at timestamptz default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  body text,
  file_url text,
  file_name text,
  file_type text,
  created_at timestamptz default now()
);

alter table public.profiles enable row level security;
alter table public.messages enable row level security;

create policy "profiles readable by signed in users"
on public.profiles for select to authenticated using (true);

create policy "users can create own profile"
on public.profiles for insert to authenticated with check (id = auth.uid());

create policy "users can update own profile"
on public.profiles for update to authenticated using (id = auth.uid());

create policy "messages readable by participants"
on public.messages for select to authenticated
using (sender_id = auth.uid() or receiver_id = auth.uid());

create policy "messages insert by sender"
on public.messages for insert to authenticated
with check (sender_id = auth.uid());

-- Automatically create a profile when a new auth user is created.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id,email)
  values (new.id, coalesce(new.email,'user'));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Storage bucket
insert into storage.buckets (id, name, public)
values ('shared-files','shared-files',true)
on conflict (id) do nothing;

create policy "public read shared files"
on storage.objects for select
using (bucket_id = 'shared-files');

create policy "signed in users upload shared files"
on storage.objects for insert to authenticated
with check (bucket_id = 'shared-files' and (storage.foldername(name))[1] = auth.uid()::text);

create policy "users delete own shared files"
on storage.objects for delete to authenticated
using (bucket_id = 'shared-files' and owner_id = auth.uid()::text);

-- Enable realtime for messages (safe if already enabled; remove table first if your project reports a duplicate).
do $$
begin
  alter publication supabase_realtime add table public.messages;
exception when duplicate_object then
  null;
end $$;
